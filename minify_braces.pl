#!/usr/bin/perl
use strict;
use warnings;

# 1. 処理対象のファイル名 (パスを含めて記述可能)
my $target_file = './rust/src/submit.rs'; 

# 2. ファイルの先頭に追加したいヘッダー文字列
my $header_text = <<'EOF';
// -----------------------------------------------------
// ファイル結合して文字列圧縮したから提出時動作確認
// -----------------------------------------------------
EOF

# =======================================================
# 処理開始
# =======================================================

# ファイルが存在するか確認
unless (-e $target_file) {
    die "エラー: ファイル '$target_file' が見つかりません。\n";
}

# 1. ファイル読み込み (Read)
my $content;
{
    open my $fh, '<', $target_file or die "読み込みエラー ($target_file): $!";
    local $/; # スラープモード（ファイル全体を一気に読む）
    $content = <$fh>;
    close $fh;
}

# -------------------------------------------------------
# 定義: 正規表現
# -------------------------------------------------------
# ダブルクォート文字列 (エスケープ対応)
my $str_re = qr/"(?:[^"\\]|\\.)*"/;

# ブロック抽出 (再帰的)
my $block_re;
$block_re = qr/
    \{                  # 開き括弧
    (?:
        $str_re         # 文字列ならスキップ
        |
        [^{}"]++        # { } " 以外の文字
        |
        (??{ $block_re }) # 再帰呼び出し
    )*
    \}                  # 閉じ括弧
/x;

# -------------------------------------------------------
# 実行: ミニファイ処理
# -------------------------------------------------------
# 外側のブロックを見つけて関数へ渡す
$content =~ s/($block_re)/minimize_safe($1)/ge;

# -------------------------------------------------------
# 実行: ヘッダー追加
# -------------------------------------------------------
$content = $header_text . "\n" . $content;

# -------------------------------------------------------
# 2. ファイル上書き保存 (Write)
# -------------------------------------------------------
open my $out_fh, '>', $target_file or die "書き込みエラー ($target_file): $!";
print $out_fh $content;
close $out_fh;


# -------------------------------------------------------
# 関数: 文字列の中身を守りつつ空白削除
# -------------------------------------------------------
sub minimize_safe {
	my $text = shift;

    # $1: 文字列 ("...") -> そのまま返す ($1)
    # $2: 改行を含む空白 (\s*\n\s*) -> " " (半角スペース) にする！
    $text =~ s/($str_re)|(\s*\n\s*)/
        defined $1 ? $1 : " " 
    /gex;

    # 整形: 連続するスペースは1つにまとめる
    $text =~ s/ {2,}/ /g;

    # 整形: { の直後と } の直前のスペースは不要なので削除
    # (ここはくっついても {code} となり文法エラーになりにくいため)
    $text =~ s/\{\s+/{/g;
    $text =~ s/\s+\}/}/g;

    return $text;
}